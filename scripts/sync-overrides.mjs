#!/usr/bin/env node
// Fetches the vinyl-image override sheet (public Google Sheet) and writes a
// TypeScript module at lib/vinyl-overrides.ts. Re-run whenever the sheet
// changes: `npm run sync-overrides`.
//
// Sheet columns:
//   A — Album   (Discogs release URL, used to extract the release ID)
//   B — Image Link  (direct Discogs image URL to use)
//   C — Notes  (empty = use as photo; non-empty = use as SVG color source)

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const SHEET_ID = "1UW3CLv5HQUVMdl-HjI1qzeNfrAmmZLlnE3isN-zo2Ak";
const CSV_URL = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/export?format=csv`;

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "..", "lib", "vinyl-overrides.ts");

// Minimal RFC-4180-ish CSV parser. Handles quoted fields with embedded
// commas/newlines/escaped quotes. Returns string[][].
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          cell += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        cell += ch;
      }
    } else {
      if (ch === '"') {
        inQuotes = true;
      } else if (ch === ",") {
        row.push(cell);
        cell = "";
      } else if (ch === "\n" || ch === "\r") {
        if (ch === "\r" && text[i + 1] === "\n") i++;
        row.push(cell);
        rows.push(row);
        row = [];
        cell = "";
      } else {
        cell += ch;
      }
    }
  }
  if (cell.length > 0 || row.length > 0) {
    row.push(cell);
    rows.push(row);
  }
  return rows;
}

function extractReleaseId(url) {
  const m = url.match(/\/release\/(\d+)/);
  return m ? Number(m[1]) : null;
}

// Pull a human label out of the Discogs URL slug:
// .../release/12345-Artist-Name-Album-Title → "Artist Name — Album Title"
// First hyphen-separated chunk is the artist, rest is the title.
function extractTitle(url) {
  const m = url.match(/\/release\/\d+-(.+?)(?:\?|$|\/)/);
  if (!m) return null;
  const slug = m[1].replace(/[-_]+/g, " ").trim();
  // Heuristic split: try to find a clean break — many slugs are
  // "Artist-Album" but Discogs doesn't mark the boundary. Just return the
  // whole slug; readable enough for an audit view.
  return decodeURIComponent(slug).replace(/\s+/g, " ");
}

async function main() {
  console.log(`Fetching ${CSV_URL}`);
  const res = await fetch(CSV_URL);
  if (!res.ok) {
    console.error(`Sheet fetch failed: ${res.status} ${res.statusText}`);
    process.exit(1);
  }
  const text = await res.text();
  const rows = parseCsv(text);
  if (rows.length === 0) {
    console.error("Empty sheet");
    process.exit(1);
  }

  // First row = header; skip it.
  const dataRows = rows.slice(1);

  /** @type {Array<{releaseId: number, imageUrl: string, kind: "photo"|"svg", note: string|null}>} */
  const entries = [];
  let skipped = 0;
  for (const r of dataRows) {
    const [albumUrl = "", imageUrl = "", note = ""] = r;
    const releaseId = extractReleaseId(albumUrl.trim());
    const url = imageUrl.trim();
    if (!releaseId || !url) {
      if (albumUrl.trim() || imageUrl.trim()) skipped++;
      continue;
    }
    const cleanNote = note.trim();
    entries.push({
      releaseId,
      imageUrl: url,
      kind: cleanNote ? "svg" : "photo",
      note: cleanNote || null,
    });
  }

  entries.sort((a, b) => a.releaseId - b.releaseId);

  const out =
    `// AUTO-GENERATED by scripts/sync-overrides.mjs. Do not edit by hand.\n` +
    `// Source: https://docs.google.com/spreadsheets/d/${SHEET_ID}\n` +
    `// Regenerate with: npm run sync-overrides\n\n` +
    `export type VinylOverride = {\n` +
    `  imageUrl: string;\n` +
    `  // "photo" = use as the vinyl image (cropped & circle-masked normally).\n` +
    `  // "svg"   = don't show a photo; sample the image's outer color and render\n` +
    `  //          the SVG fallback in that color.\n` +
    `  kind: "photo" | "svg";\n` +
    `  // Free-form note from the sheet (e.g. "Outer green color"). Informational.\n` +
    `  note: string | null;\n` +
    `};\n\n` +
    `const OVERRIDES: Readonly<Record<number, VinylOverride>> = {\n` +
    entries
      .map(
        (e) =>
          `  ${e.releaseId}: { imageUrl: ${JSON.stringify(e.imageUrl)}, kind: ${JSON.stringify(e.kind)}, note: ${JSON.stringify(e.note)} },`,
      )
      .join("\n") +
    `\n};\n\n` +
    `export function getVinylOverride(releaseId: number): VinylOverride | null {\n` +
    `  return OVERRIDES[releaseId] ?? null;\n` +
    `}\n`;

  await writeFile(OUT, out, "utf8");
  console.log(`Wrote ${entries.length} overrides to ${OUT}${skipped ? ` (skipped ${skipped} malformed row${skipped > 1 ? "s" : ""})` : ""}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
